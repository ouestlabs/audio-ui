/** A registry item's `css` object, written as a stylesheet. */
export function skinSheet(
  css: Record<string, Record<string, string>>,
  source: string
): string {
  const rules = Object.entries(css).map(([selector, declarations]) => {
    const body = Object.entries(declarations)
      .map(([property, value]) => `  ${property}: ${value};`)
      .join("\n");
    return `${selector} {\n${body}\n}`;
  });
  return `/* Generated by registry:build from bases/shared/audio-ui/skins/${source}. */\n${rules.join("\n\n")}\n`;
}

const UTILITY = /^@utility\s+([\w-]+)$/;

/** A skin as plain CSS, for a project with no Tailwind: its utilities (`@utility audio-body`) become classes. */
export function plainSkinSheet(
  css: Record<string, Record<string, string>>,
  source: string
): string {
  return skinSheet(
    Object.fromEntries(
      Object.entries(css).map(([selector, declarations]) => [
        selector.replace(UTILITY, ".$1"),
        declarations,
      ])
    ),
    source
  );
}
