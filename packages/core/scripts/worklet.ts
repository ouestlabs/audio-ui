/**
 * Bundles the clip player's processor (`src/audio/playback/worklet.ts`) into
 * one minified module and writes it, as a string, to `worklet-source.ts`:
 * what a context loads with `audioWorklet.addModule`, whatever bundler the
 * project that installs the package uses.
 *
 * The file also keeps a hash of the sources the bundle was made from. A test
 * hashes them again and fails when they changed without `bun run
 * worklet:build`: the bundle itself can differ from one Bun to the next, the
 * sources cannot.
 */

const PLAYBACK = `${import.meta.dir}/../src/audio/playback`;
const ENTRY = `${PLAYBACK}/worklet.ts`;
const OUTPUT = `${PLAYBACK}/worklet-source.ts`;
const RELATIVE_IMPORT = /from "(\.{1,2}\/[^"]+\.ts)"/g;

/** The files the entry imports, itself included, following relative imports. */
async function inputsOf(entry: string): Promise<string[]> {
  const seen = new Set<string>();
  const visit = async (path: string) => {
    if (seen.has(path)) {
      return;
    }
    seen.add(path);
    const source = await Bun.file(path).text();
    const folder = path.slice(0, path.lastIndexOf("/"));
    await Promise.all(
      [...source.matchAll(RELATIVE_IMPORT)].map(([, specifier]) =>
        visit(new URL(specifier as string, `file://${folder}/`).pathname)
      )
    );
  };
  await visit(new URL(`file://${entry}`).pathname);
  return [...seen].sort();
}

/** A hash of the bundle's sources: their paths from the package and their text. */
export async function workletInputsHash(): Promise<string> {
  const root = new URL(`file://${import.meta.dir}/../`).pathname;
  const hasher = new Bun.CryptoHasher("sha256");
  const paths = await inputsOf(ENTRY);
  const texts = await Promise.all(paths.map((path) => Bun.file(path).text()));
  for (const [index, path] of paths.entries()) {
    hasher.update(path.slice(root.length));
    hasher.update(texts[index] as string);
  }
  return hasher.digest("hex");
}

/** The processor, bundled and minified. */
export async function bundleWorklet(): Promise<string> {
  const result = await Bun.build({
    entrypoints: [ENTRY],
    format: "esm",
    minify: true,
    target: "browser",
  });
  const [output] = result.outputs;
  if (!(result.success && output)) {
    throw new Error(result.logs.map(String).join("\n"));
  }
  return (await output.text()).trim();
}

if (import.meta.main) {
  const [code, hash] = await Promise.all([
    bundleWorklet(),
    workletInputsHash(),
  ]);
  await Bun.write(
    OUTPUT,
    `// Generated by \`bun run worklet:build\` from worklet.ts: do not edit.

/** A hash of the sources this bundle was made from, checked by a test. */
export const CLIP_PLAYER_WORKLET_INPUTS = "${hash}";

/**
 * The clip player's processor, as the source of a module: load it into a
 * context with \`audioWorklet.addModule\` (from a Blob URL), then make a player
 * with \`new AudioWorkletNode(context, CLIP_PLAYER_PROCESSOR)\`.
 */
export const CLIP_PLAYER_WORKLET = ${JSON.stringify(code)};
`
  );
  // Formatted as the linter would, so that `lint:fix` leaves it as written.
  await Bun.$`bunx biome format --write ${OUTPUT}`.quiet();
}
