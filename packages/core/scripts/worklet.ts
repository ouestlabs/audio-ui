/**
 * Bundles the code that runs off the main thread into one minified module
 * each, written as a string: the clip player's processor
 * (`src/audio/playback/worklet.ts` to `worklet-source.ts`), what a context
 * loads with `audioWorklet.addModule`, and the loader of streamed recordings
 * (`loader-worker.ts` to `loader-worker-source.ts`), what a page starts a
 * Worker from, whatever bundler the project that installs the package uses.
 *
 * Each file also keeps a hash of the sources its bundle was made from. A test
 * hashes them again and fails when they changed without `bun run
 * worklet:build`: the bundle itself can differ from one Bun to the next, the
 * sources cannot.
 */

const PLAYBACK = `${import.meta.dir}/../src/audio/playback`;

/** Each bundle: its entry, the file it is written to, the constant that holds it and what that constant says. */
export const BUNDLES = [
  {
    constant: "CLIP_PLAYER_WORKLET",
    doc: `The clip player's processor, as the source of a module: load it into a
 * context with \`audioWorklet.addModule\` (from a Blob URL), then make a player
 * with \`new AudioWorkletNode(context, CLIP_PLAYER_PROCESSOR)\`.`,
    entry: `${PLAYBACK}/worklet.ts`,
    output: `${PLAYBACK}/worklet-source.ts`,
  },
  {
    constant: "RECORDING_LOADER_WORKER",
    doc: `The loader of streamed recordings, as the source of a module: start it
 * with \`new Worker(url, { type: "module" })\` (from a Blob URL), then post it
 * \`RecordingLoaderMessage\`s.`,
    entry: `${PLAYBACK}/loader-worker.ts`,
    output: `${PLAYBACK}/loader-worker-source.ts`,
  },
] as const;

const RELATIVE_IMPORT = /from "(\.{1,2}\/[^"]+\.ts)"/g;

/** The files the entry imports, itself included, following relative imports. */
async function inputsOf(entry: string): Promise<string[]> {
  const seen = new Set<string>();
  const visit = async (path: string) => {
    if (seen.has(path)) {
      return;
    }
    seen.add(path);
    const source = await Bun.file(path).text();
    const folder = path.slice(0, path.lastIndexOf("/"));
    await Promise.all(
      [...source.matchAll(RELATIVE_IMPORT)].map(([, specifier]) =>
        visit(new URL(specifier as string, `file://${folder}/`).pathname)
      )
    );
  };
  await visit(new URL(`file://${entry}`).pathname);
  return [...seen].sort();
}

/** A hash of a bundle's sources: their paths from the package and their text. */
export async function inputsHash(entry: string): Promise<string> {
  const root = new URL(`file://${import.meta.dir}/../`).pathname;
  const hasher = new Bun.CryptoHasher("sha256");
  const paths = await inputsOf(entry);
  const texts = await Promise.all(paths.map((path) => Bun.file(path).text()));
  for (const [index, path] of paths.entries()) {
    hasher.update(path.slice(root.length));
    hasher.update(texts[index] as string);
  }
  return hasher.digest("hex");
}

/** An entry, bundled and minified. */
async function bundle(entry: string): Promise<string> {
  const result = await Bun.build({
    entrypoints: [entry],
    format: "esm",
    minify: true,
    target: "browser",
  });
  const [output] = result.outputs;
  if (!(result.success && output)) {
    throw new Error(result.logs.map(String).join("\n"));
  }
  return (await output.text()).trim();
}

if (import.meta.main) {
  await Promise.all(
    BUNDLES.map(async ({ constant, doc, entry, output }) => {
      const [code, hash] = await Promise.all([
        bundle(entry),
        inputsHash(entry),
      ]);
      const name = entry.slice(entry.lastIndexOf("/") + 1);
      await Bun.write(
        output,
        `// Generated by \`bun run worklet:build\` from ${name}: do not edit.

/** A hash of the sources this bundle was made from, checked by a test. */
export const ${constant}_INPUTS = "${hash}";

/**
 * ${doc}
 */
export const ${constant} = ${JSON.stringify(code)};
`
      );
      // Formatted as the linter would, so that `lint:fix` leaves it as written.
      await Bun.$`bunx biome format --write ${output}`.quiet();
    })
  );
}
